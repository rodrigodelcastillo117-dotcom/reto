create or replace function v2.refresh_soccer_secondary_learning_v1()
returns jsonb language plpgsql security definer set search_path='v2','public','pg_temp' as $$
declare n int:=0;
begin
  with s as (
    select distinct on(p.espn_event_id,p.market_key,p.model_version) p.*
    from v2.soccer_secondary_prediction_v1 p
    where p.temporal_safe and p.decision_time<p.kickoff
    order by p.espn_event_id,p.market_key,p.model_version,p.decision_time desc
  ), x as (
    select s.*,m.home_score hs,m.away_score aws,m.status result_status
    from s cross join lateral public.buscar_marcador(s.espn_event_id) m
    where m.home_score is not null and m.away_score is not null
      and lower(coalesce(m.status,'')) in ('post','final','finished','status_final','status_full_time')
  ), ins as (
    insert into v2.model_learning_observation
      (source_system,source_key,espn_event_id,sport,league,market,model_version,eval_window,snapshot_at,kickoff,
       temporal_safe,promotion_eligible,n_classes,p1,p2,outcome_idx,line,score_home,score_away,meta)
    select 'SOCCER_SECONDARY_V1',concat_ws('|','SOC2',espn_event_id,model_version,market_key),espn_event_id,
      'soccer',endpoint,
      case market_key when 'BTTS' then 'BTTS' else 'Over/Under '||line::text end,
      model_version,'pregame_latest',decision_time,kickoff,true,true,2,p_yes/100.0,p_no/100.0,
      case when market_key='BTTS' then case when hs>0 and aws>0 then 1 else 2 end
           else case when (hs+aws)>line then 1 else 2 end end,
      line,hs,aws,jsonb_build_object('market_key',market_key,'model_status',model_status,'feature_snapshot',feature_snapshot)
    from x
    on conflict(source_key) do nothing returning 1
  ) select count(*) into n from ins;
  return jsonb_build_object('new_observations',n,'total_secondary_observations',
    (select count(*) from v2.model_learning_observation where source_system='SOCCER_SECONDARY_V1'));
end $$;
